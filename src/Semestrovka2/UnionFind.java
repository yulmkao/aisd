package Semestrovka2;

class UnionFind {
    // parent[i] — номер родителя/корня компоненты, в которой лежит вершина i
    private final int[] parent;
    // rank[i] — «ранг»/приблизительная высота дерева, подвешенного в корне i
    private final int[] rank;

    /**
     * Инициализация Union-Find для n вершин (0..n-1).
     * Вначале каждая вершина лежит в своей собственной компоненте.
     */

    public UnionFind(int n) {
        parent = new int[n];
        rank   = new int[n];
        for (int i = 0; i < n; i++) {
            parent[i] = i;   // каждая вершина — корень своей компоненты
            rank[i] = 0;   // высота изначально 0
        }
    }

    /**
     * Находит корень компоненты, в которой лежит вершина x.
     * Одновременно делает сжатие путей: переписывает parent[x] так,
     * чтобы x в следующий раз указывал сразу на корень (а не на промежуточную вершину).
     */
    private int find(int x) {
        if (parent[x] != x) {
            // 1) рекурсивно находим корень компоненты;
            // 2) по возвращении переписываем parent[x] на корень — сжимаем путь.
            parent[x] = find(parent[x]);
        }
        return parent[x]; // возвращаем корень компоненты
    }

    /**
     * Объединить компоненты, в которых лежат вершины x и y.
     * Возвращает:
     *  true — если объединение прошло (x и y были в разных компонентах),
     *  false — если x и y уже в одной компоненте (цикл).
     */
    public boolean union(int x, int y) {
        int px = find(x); // корень компоненты x
        int py = find(y); // корень компоненты y

        if (px == py) {
            return false; // вершины уже в одной группе => не трогаем ребро (цикл)
        }

        // Объединяем по рангу, чтобы не делать слишком высокие деревья
        if (rank[px] < rank[py]) {
            parent[px] = py;      // подвешиваем px под py
        } else if (rank[px] > rank[py]) {
            parent[py] = px;      // подвешиваем py под px
        } else {
            parent[py] = px;      // ранги равны, можно подвесить в любую сторону
            rank[px]++;           // повышаем ранг корня px, так как высота увеличилась
        }
        return true; // ребро безопасно добавляем в остов
    }
}